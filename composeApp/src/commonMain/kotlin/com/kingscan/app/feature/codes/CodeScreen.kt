package com.kingscan.app.feature.codes

import com.kingscan.app.core.ui.ScanTopBar
import com.kingscan.app.core.platform.ScannerCamera
import com.kingscan.app.core.platform.rememberGallerySaver
import com.kingscan.app.core.platform.rememberImagesImporter
import com.kingscan.app.core.platform.rememberShareLauncher
import com.kingscan.app.core.ui.BusyOverlay
import com.kingscan.app.core.ui.RgbaImageView
import com.kingscan.app.navigation.Navigator

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.text.selection.SelectionContainer
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.Text
import com.kingscan.app.core.ui.ScanTheme as MaterialTheme
import com.kingscan.app.core.ui.ScanTextButton as TextButton
import com.kingscan.app.core.ui.ScanButton as Button
import com.kingscan.app.core.ui.ScanSecondaryButton as OutlinedButton
import com.kingscan.app.core.ui.ScanCard as Card
import com.kingscan.app.core.ui.ScanTextField as OutlinedTextField
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalClipboardManager
import androidx.compose.ui.text.AnnotatedString
import androidx.compose.ui.unit.dp
import com.kingscan.app.AppGraph
import com.kingscan.app.core.codes.BarcodeValue
import com.kingscan.app.core.codes.createBarcodeCodec
import com.kingscan.app.core.imaging.RgbaImage
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

@Composable
fun CodeScreen(navigator: Navigator, onMessage: (String) -> Unit) {
    val scope = rememberCoroutineScope()
    val codec = remember { createBarcodeCodec() }
    var text by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<RgbaImage?>(null) }
    var results by remember { mutableStateOf<List<BarcodeValue>>(emptyList()) }
    var busy by remember { mutableStateOf(false) }
    var camera by remember { mutableStateOf(false) }
    var capture by remember { mutableStateOf<(() -> Unit)?>(null) }
    val clipboard = LocalClipboardManager.current
    val share = rememberShareLauncher(onMessage)
    val gallery = rememberGallerySaver(onMessage)
    fun decode(bytes: ByteArray) {
        camera = false
        scope.launch {
            busy = true
            val result = withContext(Dispatchers.Default) {
                runCatching { codec.decode(AppGraph.codec.decode(bytes, 2400)) }
            }
            busy = false
            result.fold({
                results = it
                if (it.isEmpty()) onMessage("没有识别到二维码或条码，请靠近并保持清晰")
            }, { onMessage(it.message ?: "识别失败") })
        }
    }
    val importer = rememberImagesImporter(onImages = { files ->
        busy = true
        scope.launch {
            val result = try { withContext(Dispatchers.Default) {
                runCatching {
                    files.flatMap { file ->
                        codec.decode(AppGraph.codec.decode(AppGraph.repository.readBytes(file.path), 2400))
                    }.distinct()
                }
            } } finally { files.forEach(AppGraph.repository::finishImport) }
            busy = false
            result.fold({
                results = it
                if (it.isEmpty()) onMessage("所选图片中没有识别到二维码或条码")
            }, { onMessage(it.message ?: "识别失败") })
        }
    }, onError = { busy = false; onMessage(it) }, onStart = { busy = true }, onCancel = { busy = false })
    fun output(toGallery: Boolean) {
        val image = generated ?: return
        scope.launch {
            busy = true
            val result = withContext(Dispatchers.Default) {
                runCatching { AppGraph.repository.exportCodeImage(AppGraph.codec.encodeJpeg(image, 100)) }
            }
            busy = false
            result.fold({ if (toGallery) gallery(listOf(it)) else share(it, "image/jpeg", "二维码") },
                { onMessage(it.message ?: "输出失败") })
        }
    }
    Box(Modifier.fillMaxSize()) {
        Column(Modifier.fillMaxSize().navigationBarsPadding()) {
            ScanTopBar("二维码与条码", onBack = { if (camera) camera = false else navigator.pop() })
            if (camera) {
                ScannerCamera(false, Modifier.weight(1f).fillMaxWidth(),
                    onBind = { capture = it }, onPhoto = ::decode,
                    onError = { busy = false; onMessage(it) })
                Button(onClick = { capture?.let { busy = true; it() } }, enabled = capture != null && !busy,
                    modifier = Modifier.fillMaxWidth().padding(16.dp)) { Text("拍照识别") }
            } else Column(Modifier.verticalScroll(rememberScrollState()).padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    Button(onClick = { camera = true }) { Text("相机识别") }
                    OutlinedButton(onClick = importer) { Text("从图片识别") }
                }
                results.forEach { result ->
                    Card(Modifier.fillMaxWidth()) {
                        Column(Modifier.padding(12.dp)) {
                            Text(result.format, style = MaterialTheme.typography.labelSmall)
                            SelectionContainer { Text(result.text) }
                            TextButton(onClick = { clipboard.setText(AnnotatedString(result.text)); onMessage("已复制") }) { Text("复制内容") }
                        }
                    }
                }
                OutlinedTextField(text, { text = it; generated = null }, label = { Text("文字或链接") },
                    modifier = Modifier.fillMaxWidth(), minLines = 3)
                Button(onClick = {
                    scope.launch {
                        busy = true
                        val result = withContext(Dispatchers.Default) { runCatching { codec.generate(text) } }
                        busy = false
                        result.fold({ generated = it }, { onMessage(it.message ?: "生成失败") })
                    }
                }) { Text("生成二维码") }
                generated?.let {
                    RgbaImageView(it, Modifier.fillMaxWidth().aspectRatio(1f), "生成的二维码")
                    Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                        TextButton(onClick = { output(true) }) { Text("保存到相册") }
                        TextButton(onClick = { output(false) }) { Text("分享二维码") }
                    }
                }
            }
        }
        BusyOverlay(busy, "正在处理")
    }
}
